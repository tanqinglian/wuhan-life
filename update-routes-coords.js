async function updateRouteCoords() {
  try {
    console.log('=== 更新Routes坐标数据 ===\n');
    
    const routes = await prisma.routes.findMany();
    
    for (const route of routes) {
      const coords = routeCoordinates[route.name];
      if (coords) {
        await prisma.routes.update({
          where: { id: route.id },
          data: {
            coordinates: coords
          }
        });
        console.log(`✓ 已更新: ${route.name}`);
      } else {
        console.log(`⚠ 未找到坐标: ${route.name}`);
      }
    }
    
    console.log('\n更新完成！');
    
  } catch (e) {
    console.error('错误:', e.message);
  } finally {
    await prisma.$disconnect();
  }
}

updateRouteCoords();
